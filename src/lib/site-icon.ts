// Resolves the icon for an entry: an explicit override first (ignored when
// it isn't a known slug), then the URL's hostname against SITE_ICON_HOSTS
// (longest suffix first), then the entry name normalized to a slug so
// "GitHub" with no URL still matches.
export function siteIconSlug(
  url: string,
  name: string,
  override?: string,
): string | null {
  if (override && KNOWN_SLUGS.has(override)) return override;
  const host = normHost(url);
  if (host) {
    const labels = host.split(".");
    for (let i = 0; i < labels.length - 1; i++) {
      const hit = SITE_ICON_HOSTS[labels.slice(i).join(".")];
      if (hit) return hit;
    }
  }
  const nameSlug = name.toLowerCase().replace(/[^a-z0-9]/g, "");
  return nameSlug && KNOWN_SLUGS.has(nameSlug) ? nameSlug : null;
}
