#!/usr/bin/env node
// Build-time generator for src/generated/script-integrity.ts — the expected
// script set used by the strict CSP (src/middleware.ts) and the best-effort
// runtime self-check (src/components/script-integrity-check.tsx).
//
//   node scripts/script-integrity.mjs build   # `npm run build`
//   node scripts/script-integrity.mjs stub    # write an empty manifest if missing
//
// `build` runs `next build` twice with a pinned build id: pass 1 emits the
// chunks and prerendered HTML, which are hashed into the generated module;
// pass 2 compiles that module into the (server-only) proxy + API route. The
// module never reaches a client chunk or the HTML, so pass 2's client output
// is identical to pass 1's — verified at the end, failing the build if not.
// Never commit the generated file: chunk names are content-hashed and the
// inline scripts embed the build id, so it changes on every build.
import { spawnSync } from "node:child_process";
import { createHash, randomBytes } from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUT = path.join(root, "src/generated/script-integrity.ts");
const DIST = path.join(root, ".next");

const sha256 = (data) => createHash("sha256").update(data).digest("base64");

function walk(dir, ext) {
  if (!fs.existsSync(dir)) return [];
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) => {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) return walk(p, ext);
    return e.name.endsWith(ext) ? [p] : [];
  });
}

// Inline (no `src`) script bodies, exactly as a CSP hash sees them: script
// is a raw-text element, so the bytes between the tags are its source.
export function extractInlineScripts(html) {
  const out = [];
  for (const m of html.matchAll(/<script\b([^>]*)>([\s\S]*?)<\/script>/gi)) {
    if (/\ssrc\s*=/i.test(` ${m[1]}`)) continue;
    if (m[2].trim() === "") continue;
    out.push(m[2]);
  }
  return out;
}

export function collect(distDir) {
  const staticDir = path.join(distDir, "static");
  const chunks = {};
  for (const file of walk(staticDir, ".js").sort()) {
    const rel = path.relative(staticDir, file).split(path.sep).join("/");
    chunks[`/_next/static/${rel}`] = sha256(fs.readFileSync(file));
  }
  const inline = new Set();
  for (const file of walk(path.join(distDir, "server"), ".html")) {
    for (const body of extractInlineScripts(fs.readFileSync(file, "utf8"))) {
      inline.add(sha256(body));
    }
  }
  return { generated: true, chunks, inline: [...inline].sort() };
}

function render(manifest) {
  return `// GENERATED by scripts/script-integrity.mjs during \`npm run build\`.
// Do not edit or commit — it changes on every build (see .gitignore).
import type { ScriptIntegrityManifestInterface } from "@/lib/script-integrity";

export const scriptIntegrity: ScriptIntegrityManifestInterface = ${JSON.stringify(manifest, null, 2)};
`;
}

function write(manifest) {
  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, render(manifest));
}

function nextBuild(env) {
  const res = spawnSync("npx", ["next", "build"], {
    cwd: root,
    stdio: "inherit",
    env: { ...process.env, ...env },
  });
  if (res.status !== 0) process.exit(res.status ?? 1);
}

function stub() {
  if (!fs.existsSync(OUT)) write({ generated: false, chunks: {}, inline: [] });
}

function build() {
  stub();
  const env = {
    PORTUNUS_BUILD_ID:
      process.env.PORTUNUS_BUILD_ID || randomBytes(12).toString("base64url"),
  };
  console.log("[script-integrity] pass 1/2: next build");
  nextBuild(env);
  const expected = collect(DIST);
  write(expected);
  console.log(
    `[script-integrity] hashed ${Object.keys(expected.chunks).length} chunks, ${expected.inline.length} inline scripts → ${path.relative(root, OUT)}`,
  );
  console.log("[script-integrity] pass 2/2: next build");
  nextBuild(env);
  const actual = collect(DIST);
  if (JSON.stringify(actual) !== JSON.stringify(expected)) {
    const diff = (a, b) => a.filter((x) => !b.includes(x));
    const ek = Object.entries(expected.chunks).map((e) => e.join(" "));
    const ak = Object.entries(actual.chunks).map((e) => e.join(" "));
    console.error("[script-integrity] client output changed between passes:");
    console.error({
      chunksMissing: diff(ek, ak),
      chunksNew: diff(ak, ek),
      inlineMissing: diff(expected.inline, actual.inline),
      inlineNew: diff(actual.inline, expected.inline),
    });
    process.exit(1);
  }
  console.log("[script-integrity] verified: built scripts match the manifest");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const cmd = process.argv[2];
  if (cmd === "build") build();
  else if (cmd === "stub") stub();
  else {
    console.error("usage: node scripts/script-integrity.mjs build|stub");
    process.exit(2);
  }
}
